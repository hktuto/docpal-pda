#!/usr/bin/env node
// Regenerate the backend's real-data seed artifacts from new_seed/.
// Usage: node scripts/gen-seed-real-data.mjs
//
// Sources (new_seed/):
//   - "ORIGINAL_ID + ORG_ID + Sub Inventory mapping.xlsx" (sheet "Enable Subinv Data")
//   - parts_table.xlsx (sheet "Item table")
//   - weight/KOA N.W.xls + weight/other.xls (Sheet1: col B = wcl_item_no, col C = unit weight KG)
//   - 210726.xls (Sheet1 packing list)
//
// Outputs (apps/backend/src/db/):
//   - seed-subinventories-data.ts   realSubInventories (org_id + code groups)
//   - seed-parts-data.json          { suppliers, parts } bulk master (~100k parts)
//   - seed-net-weight-data.ts       realNetWeights (grams per 1 pc)
//   - seed-order-210726.ts          order210726 / Invoices / Items
//
// Split rule (confirmed with the business): wcl_item_no = SEGMENT1 verbatim;
// supplier + part_no come from splitting on the FIRST / + - * — prefix is the
// supplier, remainder with all whitespace removed is the part_no.
// Design: docs/superpowers/specs/2026-07-27-real-master-data-and-share-groups-design.md

import XLSX from "xlsx";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const seedDir = path.join(root, "new_seed");
const outDir = path.join(root, "apps/backend/src/db");

const uid = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, "0")}`;
const HEADER = "// GENERATED by scripts/gen-seed-real-data.mjs — do not edit by hand.\n";

/** Split a wcl item no on the first / + - * → [supplier, partNo(spaces stripped)] or null. */
function splitWclItemNo(raw) {
  const s = String(raw ?? "").trim();
  const m = s.match(/[/+\-*]/);
  if (!m || m.index === 0) return null;
  const supplier = s.slice(0, m.index).trim();
  const partNo = s.slice(m.index + 1).replace(/\s+/g, "");
  if (!supplier || !partNo) return null;
  return [supplier, partNo];
}

const stripSpaces = (s) => String(s ?? "").replace(/\s+/g, "");
const ts = (v) => JSON.stringify(v);

function sheet(file, name) {
  const wb = XLSX.readFile(path.join(seedDir, file));
  return XLSX.utils.sheet_to_json(wb.Sheets[name ?? wb.SheetNames[0]], { header: 1, defval: "" });
}

// ---------------------------------------------------------------------------
// 1. Sub-inventory master (151 rows, 13 orgs) — plain (org_id,
//    secondary_inventory_name) groups.
// ---------------------------------------------------------------------------
const subRows = sheet("ORIGINAL_ID + ORG_ID + Sub Inventory mapping.xlsx", "Enable Subinv Data").slice(1);
const seenSub = new Set();
const realSubInventories = [];
for (const r of subRows) {
  const orgId = Number(r[2]);
  const secondaryInventoryName = String(r[3]).trim();
  const subinvDescription = String(r[4]).trim() || null;
  if (!Number.isInteger(orgId) || !secondaryInventoryName) continue;
  const key = `${orgId}|${secondaryInventoryName}`;
  if (seenSub.has(key)) continue;
  seenSub.add(key);
  realSubInventories.push({ orgId, secondaryInventoryName, subinvDescription });
}
writeFileSync(
  path.join(outDir, "seed-subinventories-data.ts"),
  HEADER +
    "// Source: new_seed/ORIGINAL_ID + ORG_ID + Sub Inventory mapping.xlsx (Enable Subinv Data).\n" +
    "// Plain (org_id, secondary_inventory_name) groups; sharing between stores is configured per\n" +
    "// warehouse via sub_inventory_share_members.\n" +
    `export const realSubInventories = ${JSON.stringify(realSubInventories, null, 1)};\n`
);
console.log(`sub-inventories: ${realSubInventories.length} groups (${new Set(realSubInventories.map((s) => s.orgId)).size} orgs)`);

// ---------------------------------------------------------------------------
// 2. Parts master. Dedupe keep-first on part_no (COO/brand variants collapse).
//    Rows without a delimiter are junk (ADJUSTMENT, CANCELLATION FEE, …) → skip.
// ---------------------------------------------------------------------------
const partRows = sheet("parts_table.xlsx", "Item table").slice(1);
const partMap = new Map(); // partNo → row
const supplierCodes = new Set();
let skippedJunk = 0;
for (const r of partRows) {
  const sp = splitWclItemNo(r[1]);
  if (!sp) {
    skippedJunk++;
    continue;
  }
  const [supplierCode, partNo] = sp;
  supplierCodes.add(supplierCode);
  if (partMap.has(partNo)) continue;
  partMap.set(partNo, {
    brand: supplierCode, // parts.brand — plain text, no FK
    partNo,
    wclItemNo: String(r[1]).trim(),
    description: String(r[2]).trim() || null,
  });
}
const bulkParts = [...partMap.values()];
writeFileSync(
  path.join(outDir, "seed-parts-data.json"),
  JSON.stringify({ suppliers: [...supplierCodes].sort(), parts: bulkParts })
);
console.log(
  `parts: ${bulkParts.length} distinct part_no (${partRows.length - skippedJunk - bulkParts.length} dup variants, ${skippedJunk} junk rows skipped), ${supplierCodes.size} suppliers`
);

// ---------------------------------------------------------------------------
// 3. Net weights. Col B = wcl_item_no (split like parts; whole string tried as
//    fallback for values whose delimiter is part of the size code, e.g.
//    "CF1/4CT52A"), col C = unit weight KG → grams per 1 pc.
// ---------------------------------------------------------------------------
const weightMap = new Map(); // partNo → grams
let weightNoPart = 0;
let weightBad = 0;
for (const file of ["weight/KOA N.W.xls", "weight/other.xls"]) {
  for (const r of sheet(file, "Sheet1")) {
    const raw = String(r[1] ?? "").trim();
    const kg = Number(r[2]);
    if (!raw) continue;
    if (!Number.isFinite(kg) || kg <= 0) {
      weightBad++;
      continue;
    }
    const sp = splitWclItemNo(raw);
    const candidates = sp ? [sp[1], stripSpaces(raw)] : [stripSpaces(raw)];
    const partNo = candidates.find((c) => partMap.has(c));
    if (!partNo) {
      weightNoPart++;
      continue;
    }
    if (weightMap.has(partNo)) continue;
    weightMap.set(partNo, Math.round(kg * 1000 * 1e6) / 1e6);
  }
}
const realNetWeights = [...weightMap.entries()].map(([partNo, weight]) => ({ partNo, weight }));
writeFileSync(
  path.join(outDir, "seed-net-weight-data.ts"),
  HEADER +
    "// Source: new_seed/weight/KOA N.W.xls + other.xls (col C unit weight KG → grams per 1 pc).\n" +
    `export const realNetWeights = ${JSON.stringify(realNetWeights, null, 1)};\n`
);
console.log(`net weights: ${realNetWeights.length} rows (${weightNoPart} without a matching part, ${weightBad} bad weights)`);

// ---------------------------------------------------------------------------
// 4. Receiving order 210726 — one multi-supplier order (order supplier NULL,
//    supplier per invoice; invoices are single-brand). Trailing summary rows
//    (合板/紙板/膠板) carry no invoice no → skipped by the r[3] filter.
// ---------------------------------------------------------------------------
const ORDER_ID = uid(2100);
const rows210726 = sheet("210726.xls", "Sheet1").slice(1).filter((r) => String(r[3]).trim() !== "");
const invoices = new Map(); // invoiceNo → { row, ctnSet, totalQty }
const items210726 = [];
let missingPart = 0;
for (const r of rows210726) {
  const invoiceNo = String(r[3]).trim();
  const wclItemNo = String(r[6]).trim();
  const sp = splitWclItemNo(wclItemNo);
  if (!sp || !partMap.has(sp[1])) {
    missingPart++;
    console.warn(`  skip item (part not in master): ${wclItemNo}`);
    continue;
  }
  if (!invoices.has(invoiceNo)) {
    invoices.set(invoiceNo, {
      invoiceNo,
      supplierCode: sp[0], // invoices are single-brand (verified)
      wclCompanyName: String(r[4]).trim() || null,
      ctnSet: new Set(),
      totalQty: 0,
    });
  }
  const inv = invoices.get(invoiceNo);
  if (String(r[0]).trim() !== "") inv.ctnSet.add(String(r[0]).trim());
  inv.totalQty += Number(r[7]) || 0;
  items210726.push({
    invoiceNo,
    partNo: sp[1],
    wclItemNo,
    poNo: String(r[5]).trim() || null,
    lineQty: Number(r[7]) || 0,
    ctnNo: String(r[0]).trim() || null,
    coo: String(r[10]).trim() || null,
  });
}
const invList = [...invoices.values()];
const invId = new Map(invList.map((v, i) => [v.invoiceNo, uid(3100 + i)]));
const order210726 = [
  {
    id: ORDER_ID,
    batchNo: "210726",
    supplierCode: null, // multi-supplier order — supplier lives on the invoices
    deliveryDate: "2026-07-21",
    orgId: 2,
    status: "pending",
  },
];
const order210726Invoices = invList.map((v) => ({
  id: invId.get(v.invoiceNo),
  receivingOrderId: ORDER_ID,
  invoiceNo: v.invoiceNo,
  supplierCode: v.supplierCode, // invoices carry the supplier code directly
  wclCompanyName: v.wclCompanyName,
  totalQty: v.totalQty,
  totalCtn: v.ctnSet.size || null,
  orgId: 2,
}));
const order210726Items = items210726.map((it, i) => ({
  id: uid(5000 + i),
  receivingInvoiceId: invId.get(it.invoiceNo),
  partNo: it.partNo,
  wclItemNo: it.wclItemNo,
  poNo: it.poNo,
  lineQty: it.lineQty,
  ctnNo: it.ctnNo,
  coo: it.coo,
}));
const fmtRow = (o) =>
  `{ ${Object.entries(o)
    .map(([k, v]) => `${k}: ${k === "deliveryDate" ? `new Date(${ts(v)})` : ts(v)}`)
    .join(", ")} }`;
writeFileSync(
  path.join(outDir, "seed-order-210726.ts"),
  HEADER +
    "// Source: new_seed/210726.xls — one multi-supplier pending receiving order\n" +
    "// (batch 210726, org 2, delivery 2026-07-21). Invoice supplierCode\n" +
    "// is carried directly as supplier_code. Size/G.W/產品 columns and the\n" +
    "// trailing 合板/紙板/膠板 summary rows have no schema home — dropped.\n" +
    `export const order210726 = [\n  ${order210726.map(fmtRow).join(",\n  ")},\n];\n\n` +
    `export const order210726Invoices = [\n  ${order210726Invoices.map(fmtRow).join(",\n  ")},\n];\n\n` +
    `export const order210726Items = [\n  ${order210726Items.map(fmtRow).join(",\n  ")},\n];\n`
);
console.log(
  `order 210726: ${invList.length} invoices, ${order210726Items.length} items (${missingPart} skipped), suppliers: ${[...new Set(invList.map((v) => v.supplierCode))].join(", ")}`
);
