#!/usr/bin/env node
/**
 * Generate apps/backend/src/db/seed-shelves-sz.ts from an Excel file.
 *
 * Reads the MO_NO column (format: SHELF-CODE-DATE-CODE, e.g. SZB07A-2312),
 * extracts unique shelf codes, groups them by zone prefix, and writes the
 * seed file.
 *
 * Usage:
 *   node scripts/gen-seed-shelves-sz.mjs [path-to-excel]
 *
 * Defaults to all-stock.xlsx in the repo root.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import XLSX from "xlsx";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");

const excelPath = process.argv[2]
  ? resolve(process.argv[2])
  : resolve(repoRoot, "all-stock.xlsx");

if (!existsSync(excelPath)) {
  console.error(`Excel file not found: ${excelPath}`);
  process.exit(1);
}

// --- Read Excel ---
const wb = XLSX.readFile(excelPath);
const ws = wb.Sheets[wb.SheetNames[0]];
const data = XLSX.utils.sheet_to_json(ws, { header: 1 });
const headers = data[0];
const moNoIdx = headers.indexOf("MO_NO");

if (moNoIdx < 0) {
  console.error("MO_NO column not found in Excel file");
  process.exit(1);
}

// --- Extract unique shelf codes ---
const shelfCodes = new Set();

for (let i = 1; i < data.length; i++) {
  const moNo = String(data[i][moNoIdx] || "").trim();
  if (!moNo) continue;
  // Split on last dash: shelf-code-datecode
  const lastDash = moNo.lastIndexOf("-");
  if (lastDash < 0) continue;
  const shelfCode = moNo.substring(0, lastDash).trim();
  if (shelfCode) shelfCodes.add(shelfCode);
}

const sorted = [...shelfCodes].sort();

// --- Group by zone ---
// Zone = alphabetic prefix before the first digit (e.g. SZA01A -> SZA).
// Codes with no digits (DAMAGE, DUMMY) go into the null zone.
function zoneOf(code) {
  const m = code.match(/^([A-Z]+)/);
  return m ? m[1] : null;
}

const zoneMap = new Map(); // zone -> string[]
for (const code of sorted) {
  const zone = zoneOf(code);
  if (!zoneMap.has(zone)) zoneMap.set(zone, []);
  zoneMap.get(zone).push(code);
}

// Sort zones: known zones alphabetically first, then null zone last
const zones = [...zoneMap.keys()].sort((a, b) => {
  if (a === null) return 1;
  if (b === null) return -1;
  return a.localeCompare(b);
});

// --- Generate TypeScript ---
const lines = [];
lines.push(`// SZ warehouse shelf layout — seeded when WAREHOUSE_CODE=sz (seedReferenceOnly`);
lines.push(`// in seed.ts). Same shape as seed-shelves-hk.ts: zone groups flattened into`);
lines.push(`// shelves rows. The app runs one instance per warehouse, so the SZ instance`);
lines.push(`// gets its own database seeded from this file instead of the HK layout.`);
lines.push(`//`);
lines.push(`// GENERATED by scripts/gen-seed-shelves-sz.mjs — do not edit by hand.`);
lines.push(`// Source: ${excelPath} (${sorted.length} unique shelf codes from MO_NO).`);
lines.push(``);
lines.push(`import { shelfDisplayName } from "./seed-shelves-hk.js";`);
lines.push(``);

// Helper functions
lines.push(`/** Numeric range, zero-padded: numRange("SZD", 1, 3) → SZD01, SZD02, SZD03 */`);
lines.push(`function numRange(prefix: string, start: number, end: number, pad = 2): string[] {`);
lines.push(`  return Array.from({ length: end - start + 1 }, (_, i) => \`\${prefix}\${String(start + i).padStart(pad, "0")}\`);`);
lines.push(`}`);
lines.push(``);
lines.push(`/** Letter-suffix range: letterRange("GZC11", "A", "D") → GZC11A..GZC11D */`);
lines.push(`function letterRange(base: string, from: string, to: string): string[] {`);
lines.push(`  const out: string[] = [];`);
lines.push(`  for (let c = from.charCodeAt(0); c <= to.charCodeAt(0); c++) out.push(\`\${base}\${String.fromCharCode(c)}\`);`);
lines.push(`  return out;`);
lines.push(`}`);
lines.push(``);

// Zone data
lines.push(`const szShelfZones: { zone: string | null; shelf: string[] }[] = [`);

for (const zone of zones) {
  const codes = zoneMap.get(zone);
  lines.push(`  {`);
  lines.push(`    zone: ${zone ? `"${zone}"` : "null"},`);
  lines.push(`    shelf: [`);

  // Group codes by their pattern (prefix + suffix structure)
  // e.g. SZA01A, SZA02A -> pattern "SZA##A"
  const patternGroups = new Map();
  for (const code of codes) {
    const pattern = code.replace(/\d/g, "#");
    if (!patternGroups.has(pattern)) patternGroups.set(pattern, []);
    patternGroups.get(pattern).push(code);
  }

  const patterns = [...patternGroups.keys()].sort();
  for (const pattern of patterns) {
    const groupCodes = patternGroups.get(pattern);
    // Try to express as a range
    const range = tryRange(groupCodes);
    if (range) {
      lines.push(`      // ${pattern} (${groupCodes.length})`);
      lines.push(`      ...${range},`);
    } else {
      // Explicit list
      lines.push(`      // ${pattern} (${groupCodes.length})`);
      const chunks = chunk(groupCodes, 8);
      for (const chunk of chunks) {
        lines.push(`      ${chunk.map((c) => `"${c}"`).join(", ")},`);
      }
    }
  }

  lines.push(`    ],`);
  lines.push(`  },`);
}

lines.push(`];`);
lines.push(``);

// Flatten + dedupe
lines.push(`/** Flattened { code, displayName, zone, warning? } rows ready to insert into`);
lines.push(` *  the shelves table. Deduped — shelves.code is UNIQUE. */`);
lines.push(`const seen = new Set<string>();`);
lines.push(`export const szShelves: { code: string; displayName?: string; zone: string | null; warning?: string }[] = [];`);
lines.push(`for (const z of szShelfZones) {`);
lines.push(`  for (const code of z.shelf) {`);
lines.push(`    if (seen.has(code)) continue;`);
lines.push(`    seen.add(code);`);
lines.push(`    szShelves.push({ code, displayName: shelfDisplayName(code), zone: z.zone });`);
lines.push(`  }`);
lines.push(`}`);

// --- Helpers ---
function tryRange(codes) {
  if (codes.length < 3) return null;

  // Check if all codes share the same prefix and suffix, differing only in digits
  const prefix = codes[0].match(/^([A-Z]+)/)?.[1];
  const suffix = codes[0].match(/([A-Z]+)$/)?.[1];
  if (!prefix) return null;

  const nums = [];
  for (const code of codes) {
    const p = code.match(/^([A-Z]+)/)?.[1];
    const s = code.match(/([A-Z]+)$/)?.[1];
    if (p !== prefix || s !== suffix) return null;
    const numStr = code.slice(prefix.length, code.length - (suffix?.length || 0));
    if (!/^\d+$/.test(numStr)) return null;
    nums.push(parseInt(numStr, 10));
  }

  nums.sort((a, b) => a - b);

  // Check if contiguous
  for (let i = 1; i < nums.length; i++) {
    if (nums[i] !== nums[i - 1] + 1) return null;
  }

  const pad = codes[0].match(/^([A-Z]+)(\d+)/)?.[2].length || 2;
  const start = nums[0];
  const end = nums[nums.length - 1];

  if (suffix) {
    // letterRange generates base+letter for each letter in range — but we need
    // prefix+num+suffix for each num in range. Use numRange + map instead.
    return `numRange("${prefix}", ${start}, ${end}, ${pad}).map((n) => \`\${n}${suffix}\`)`;
  }
  return `numRange("${prefix}", ${start}, ${end}, ${pad})`;
}

function chunk(arr, size) {
  const out = [];
  for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size));
  return out;
}

// --- Write ---
const output = lines.join("\n") + "\n";
const outputPath = resolve(repoRoot, "apps/backend/src/db/seed-shelves-sz.ts");
writeFileSync(outputPath, output);

console.log(`Generated ${outputPath}`);
console.log(`  ${sorted.length} unique shelf codes across ${zones.length} zones`);
